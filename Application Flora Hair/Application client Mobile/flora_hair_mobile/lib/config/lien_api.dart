/// URL de l'API chiffree par XOR — jamais en clair dans le binaire.
///
/// L'adresse se voit dans le trafic reseau du telephone (c'est normal),
/// mais elle ne doit pas etre lisible par un simple `strings` sur l'APK.
class LienApi {
  LienApi._();

  static const _k = [
    0x7A, 0x3B, 0x5C, 0x1D, 0x4E, 0x2F, 0x6A, 0x0B,
    0x58, 0x19, 0x3A, 0x5B, 0x1C, 0x4D, 0x2E, 0x6F,
  ];

  // 'https://api.florahair.online' XOR _k
  static const _d = [
    0x12, 0x4F, 0x28, 0x6D, 0x3D, 0x15, 0x45, 0x24,
    0x39, 0x69, 0x53, 0x75, 0x7A, 0x21, 0x41, 0x1D,
    0x1B, 0x53, 0x3D, 0x74, 0x3C, 0x01, 0x05, 0x65,
    0x34, 0x70, 0x54, 0x3E,
  ];

  // 'https://www.florahair.online' XOR _k
  static const _s = [
    0x12, 0x4F, 0x28, 0x6D, 0x3D, 0x15, 0x45, 0x24,
    0x2F, 0x6E, 0x4D, 0x75, 0x7A, 0x21, 0x41, 0x1D,
    0x1B, 0x53, 0x3D, 0x74, 0x3C, 0x01, 0x05, 0x65,
    0x34, 0x70, 0x54, 0x3E,
  ];

  static String _decode(List<int> data) {
    final buf = StringBuffer();
    for (var i = 0; i < data.length; i++) {
      buf.writeCharCode(data[i] ^ _k[i % _k.length]);
    }
    return buf.toString();
  }

  static String get apiUrl => _decode(_d);
  static String get siteUrl => _decode(_s);
}
