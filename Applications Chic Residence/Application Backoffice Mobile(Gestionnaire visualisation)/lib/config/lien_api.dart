/// URL de l'API chiffree par XOR — jamais en clair dans le binaire.
class LienApi {
  LienApi._();

  static const _k = [
    0x7A, 0x3B, 0x5C, 0x1D, 0x4E, 0x2F, 0x6A, 0x0B,
    0x58, 0x19, 0x3A, 0x5B, 0x1C, 0x4D, 0x2E, 0x6F,
  ];

  // 'https://api-production-4e71.up.railway.app' XOR _k
  static const _d = [
    0x12, 0x4F, 0x28, 0x6D, 0x3D, 0x15, 0x45, 0x24,
    0x39, 0x69, 0x53, 0x76, 0x6C, 0x3F, 0x41, 0x0B,
    0x0F, 0x58, 0x28, 0x74, 0x21, 0x41, 0x47, 0x3F,
    0x3D, 0x2E, 0x0B, 0x75, 0x69, 0x3D, 0x00, 0x1D,
    0x1B, 0x52, 0x30, 0x6A, 0x2F, 0x56, 0x44, 0x6A,
    0x28, 0x69,
  ];

  static String _decode(List<int> data) {
    final buf = StringBuffer();
    for (var i = 0; i < data.length; i++) {
      buf.writeCharCode(data[i] ^ _k[i % _k.length]);
    }
    return buf.toString();
  }

  static String get apiUrl => _decode(_d);
}
